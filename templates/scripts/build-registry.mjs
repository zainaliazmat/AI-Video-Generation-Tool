// Template discovery → typed registry codegen.
//
// Scans templates/<id>/ folders that contain BOTH a manifest.json and a
// Component.tsx, and emits templates/registry.generated.ts with STATIC imports
// of each component + manifest. Static imports are the one approach that
// survives both the Remotion CLI bundler and Next.js without surprises (no
// require.context / dynamic import).
//
// "Drop a folder in" → re-run this (it runs on dev/build/render/studio). Core
// never hardcodes a template; everything resolves through the generated registry.
import {readdirSync, existsSync, writeFileSync} from 'node:fs';
import {dirname, resolve, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {readFileSync} from 'node:fs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const templatesDir = resolve(__dirname, '..');
const outFile = resolve(templatesDir, 'registry.generated.ts');

function discover() {
  const found = [];
  for (const entry of readdirSync(templatesDir, {withFileTypes: true})) {
    if (!entry.isDirectory() || entry.name === 'scripts' || entry.name === 'node_modules') {
      continue;
    }
    const dir = join(templatesDir, entry.name);
    const manifestPath = join(dir, 'manifest.json');
    const componentPath = join(dir, 'Component.tsx');
    if (!existsSync(manifestPath) || !existsSync(componentPath)) {
      continue;
    }
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    if (!manifest.id || typeof manifest.id !== 'string') {
      throw new Error(`[build-registry] ${entry.name}/manifest.json is missing a string "id"`);
    }
    found.push({folder: entry.name, id: manifest.id});
  }
  // Deterministic order — codegen output must be stable across runs.
  found.sort((a, b) => a.id.localeCompare(b.id));
  return found;
}

function generate(templates) {
  const header =
    '// AUTO-GENERATED by scripts/build-registry.mjs — DO NOT EDIT.\n' +
    '// Re-run `npm run build-registry` (auto-runs on dev/build/render/studio).\n\n';

  if (templates.length === 0) {
    return (
      header +
      "import type {ComponentType} from 'react';\n" +
      "import type {Manifest} from './sdk';\n\n" +
      'export interface TemplateEntry {\n' +
      '  manifest: Manifest;\n' +
      '  component: ComponentType<any>;\n' +
      '}\n\n' +
      'export const registry: Record<string, TemplateEntry> = {};\n\n' +
      'export const templateIds: string[] = Object.keys(registry);\n'
    );
  }

  const imports = templates
    .map(
      (t, i) =>
        `import tpl${i}_component from './${t.folder}/Component';\n` +
        `import tpl${i}_manifest from './${t.folder}/manifest.json';`,
    )
    .join('\n');

  const entries = templates
    .map(
      (t, i) =>
        `  ${JSON.stringify(t.id)}: {manifest: tpl${i}_manifest as Manifest, component: tpl${i}_component},`,
    )
    .join('\n');

  return (
    header +
    "import type {ComponentType} from 'react';\n" +
    "import type {Manifest} from './sdk';\n" +
    imports +
    '\n\n' +
    'export interface TemplateEntry {\n' +
    '  manifest: Manifest;\n' +
    '  component: ComponentType<any>;\n' +
    '}\n\n' +
    'export const registry: Record<string, TemplateEntry> = {\n' +
    entries +
    '\n};\n\n' +
    'export const templateIds: string[] = Object.keys(registry);\n'
  );
}

const templates = discover();
writeFileSync(outFile, generate(templates), 'utf8');
console.log(
  `[build-registry] ${templates.length} template(s) -> registry.generated.ts` +
    (templates.length ? `: ${templates.map((t) => t.id).join(', ')}` : ' (empty)'),
);

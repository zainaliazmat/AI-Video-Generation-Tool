// Template discovery → typed registry codegen.
//
// Scans templates/<id>/ folders with a manifest.json plus their entry file, and
// emits templates/registry.generated.ts with STATIC imports. Static imports are
// the one approach that survives both the Remotion CLI bundler and Next.js (no
// require.context / dynamic import).
//
// Kind-aware: a `transition`-kind template provides a presentation.tsx (a
// <TransitionSeries> presentation factory); every other kind provides a
// Component.tsx (a TemplateProps component). The generated registry is a
// discriminated union (type: 'render' | 'transition') so the two can't be mixed
// up downstream.
import {readdirSync, existsSync, writeFileSync, readFileSync} from 'node:fs';
import {dirname, resolve, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const templatesDir = resolve(__dirname, '..');
const outFile = resolve(templatesDir, 'registry.generated.ts');

function hasEntry(dir, base) {
  return existsSync(join(dir, `${base}.tsx`)) || existsSync(join(dir, `${base}.ts`));
}

function discover() {
  const found = [];
  for (const entry of readdirSync(templatesDir, {withFileTypes: true})) {
    if (!entry.isDirectory() || entry.name === 'scripts' || entry.name === 'node_modules') {
      continue;
    }
    const dir = join(templatesDir, entry.name);
    const manifestPath = join(dir, 'manifest.json');
    if (!existsSync(manifestPath)) continue;
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    if (!manifest.id || typeof manifest.id !== 'string') {
      throw new Error(`[build-registry] ${entry.name}/manifest.json is missing a string "id"`);
    }
    const isTransition = manifest.kind === 'transition';
    const base = isTransition ? 'presentation' : 'Component';
    if (!hasEntry(dir, base)) continue; // folder missing its entry file — skip
    found.push({folder: entry.name, id: manifest.id, isTransition, base});
  }
  // Deterministic order — codegen output must be stable across runs.
  found.sort((a, b) => a.id.localeCompare(b.id));
  return found;
}

function generate(templates) {
  const header =
    '// AUTO-GENERATED by scripts/build-registry.mjs — DO NOT EDIT.\n' +
    '// Re-run `npm run build-registry` (auto-runs on dev/build/render/studio).\n\n' +
    "import type {Manifest, TemplateEntry} from './sdk';\n";

  const imports = templates
    .map((t, i) => {
      const m = `import tpl${i}_manifest from './${t.folder}/manifest.json';`;
      const e = t.isTransition
        ? `import tpl${i}_presentation from './${t.folder}/presentation';`
        : `import tpl${i}_component from './${t.folder}/Component';`;
      return `${m}\n${e}`;
    })
    .join('\n');

  const entries = templates
    .map((t, i) =>
      t.isTransition
        ? `  ${JSON.stringify(t.id)}: {type: 'transition', manifest: tpl${i}_manifest as Manifest, presentation: tpl${i}_presentation},`
        : `  ${JSON.stringify(t.id)}: {type: 'render', manifest: tpl${i}_manifest as Manifest, component: tpl${i}_component},`,
    )
    .join('\n');

  const body =
    templates.length === 0
      ? 'export const registry: Record<string, TemplateEntry> = {};\n'
      : 'export const registry: Record<string, TemplateEntry> = {\n' + entries + '\n};\n';

  return (
    header +
    (imports ? imports + '\n\n' : '\n') +
    body +
    '\nexport const templateIds: string[] = Object.keys(registry);\n'
  );
}

const templates = discover();
writeFileSync(outFile, generate(templates), 'utf8');
const labels = templates.map((t) => `${t.id}${t.isTransition ? ' (transition)' : ''}`);
console.log(
  `[build-registry] ${templates.length} template(s) -> registry.generated.ts` +
    (labels.length ? `: ${labels.join(', ')}` : ' (empty)'),
);
